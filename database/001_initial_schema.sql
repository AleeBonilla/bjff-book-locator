-- Rechaza ciclos, relaciones entre esquemas y más de un terminal por rama.
CREATE OR REPLACE FUNCTION validate_scheme_level_tree()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  ancestor_has_terminal   BOOLEAN := false;
  descendant_has_terminal BOOLEAN := false;
BEGIN
  IF TG_OP = 'UPDATE'
     AND NEW.scheme_id IS DISTINCT FROM OLD.scheme_id
     AND EXISTS (
       SELECT 1
       FROM map_layer_scheme_levels AS mlsl
       JOIN map_layers AS ml
         ON ml.map_layer_id = mlsl.map_layer_id
       WHERE mlsl.scheme_level_id = NEW.scheme_level_id
         AND ml.scheme_id <> NEW.scheme_id
     )
  THEN
    RAISE EXCEPTION 'El nivel está asociado con un MapLayer de otro esquema';
  END IF;

  IF TG_OP = 'UPDATE'
     AND (
       NEW.scheme_id IS DISTINCT FROM OLD.scheme_id
       OR NEW.parent_level_id IS DISTINCT FROM OLD.parent_level_id
     )
     AND EXISTS (
       SELECT 1
       FROM map_layer_scheme_levels AS mlsl
       JOIN map_layer_svg_assignments AS a
         ON a.map_layer_id = mlsl.map_layer_id
       WHERE mlsl.scheme_level_id = NEW.scheme_level_id
     )
  THEN
    RAISE EXCEPTION 'Debe eliminar las asignaciones SVG antes de mover el nivel';
  END IF;

  IF TG_OP = 'UPDATE' AND NEW.parent_level_id IS NOT NULL AND EXISTS (
    WITH RECURSIVE descendants AS (
      SELECT sl.scheme_level_id
      FROM scheme_levels AS sl
      WHERE sl.scheme_id = NEW.scheme_id
        AND sl.parent_level_id = NEW.scheme_level_id
      UNION ALL
      SELECT child.scheme_level_id
      FROM scheme_levels AS child
      JOIN descendants AS parent
        ON child.parent_level_id = parent.scheme_level_id
      WHERE child.scheme_id = NEW.scheme_id
    )
    SELECT 1
    FROM descendants
    WHERE scheme_level_id = NEW.parent_level_id
  ) THEN
    RAISE EXCEPTION 'La relación propuesta produciría un ciclo de niveles';
  END IF;

  IF NEW.parent_level_id IS NOT NULL THEN
    WITH RECURSIVE ancestors AS (
      SELECT sl.scheme_level_id, sl.parent_level_id, sl.is_search_terminal
      FROM scheme_levels AS sl
      WHERE sl.scheme_id = NEW.scheme_id
        AND sl.scheme_level_id = NEW.parent_level_id
      UNION ALL
      SELECT parent.scheme_level_id,
             parent.parent_level_id,
             parent.is_search_terminal
      FROM scheme_levels AS parent
      JOIN ancestors AS child
        ON parent.scheme_level_id = child.parent_level_id
      WHERE parent.scheme_id = NEW.scheme_id
    )
    SELECT EXISTS (
      SELECT 1 FROM ancestors WHERE is_search_terminal
    ) INTO ancestor_has_terminal;
  END IF;

  WITH RECURSIVE descendants AS (
    SELECT sl.scheme_level_id, sl.is_search_terminal
    FROM scheme_levels AS sl
    WHERE sl.scheme_id = NEW.scheme_id
      AND sl.parent_level_id = NEW.scheme_level_id
    UNION ALL
    SELECT child.scheme_level_id, child.is_search_terminal
    FROM scheme_levels AS child
    JOIN descendants AS parent
      ON child.parent_level_id = parent.scheme_level_id
    WHERE child.scheme_id = NEW.scheme_id
  )
  SELECT EXISTS (
    SELECT 1 FROM descendants WHERE is_search_terminal
  ) INTO descendant_has_terminal;

  IF NEW.is_search_terminal AND descendant_has_terminal THEN
    RAISE EXCEPTION 'Un terminal de búsqueda no puede tener otro terminal descendiente';
  END IF;

  IF ancestor_has_terminal AND (NEW.is_search_terminal OR descendant_has_terminal) THEN
    RAISE EXCEPTION 'Una rama no puede contener dos terminales de búsqueda';
  END IF;

  RETURN NEW;
END;
$$;

-- Limita los cambios de scheme_levels a esquemas en DRAFT.
CREATE OR REPLACE FUNCTION ensure_scheme_levels_are_draft()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  affected_scheme_id INTEGER;
  affected_status    scheme_status;
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.scheme_id IS DISTINCT FROM NEW.scheme_id AND EXISTS (
    SELECT 1
    FROM schemes
    WHERE scheme_id IN (OLD.scheme_id, NEW.scheme_id)
      AND status <> 'DRAFT'
  ) THEN
    RAISE EXCEPTION 'Los niveles solo pueden moverse entre esquemas en estado DRAFT';
  END IF;

  affected_scheme_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.scheme_id ELSE NEW.scheme_id END;

  SELECT status
  INTO affected_status
  FROM schemes
  WHERE scheme_id = affected_scheme_id;

  IF affected_status <> 'DRAFT' THEN
    RAISE EXCEPTION 'Los niveles solo pueden modificarse cuando el esquema está en DRAFT';
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;

-- Aplica la restricción de etapa a toda escritura de niveles.
CREATE TRIGGER scheme_levels_require_draft
BEFORE INSERT OR UPDATE OR DELETE
ON scheme_levels
FOR EACH ROW EXECUTE FUNCTION ensure_scheme_levels_are_draft();

-- Valida la topología cuando cambia el padre, esquema o terminal del nivel.
CREATE TRIGGER scheme_levels_validate_tree
BEFORE INSERT OR UPDATE OF scheme_id, parent_level_id, is_search_terminal
ON scheme_levels
FOR EACH ROW EXECUTE FUNCTION validate_scheme_level_tree();

-- Comprueba una raíz única y exactamente un terminal en cada rama raíz-hoja.
CREATE OR REPLACE FUNCTION assert_scheme_search_coverage(p_scheme_id INTEGER)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
  IF (
    SELECT count(*)
    FROM scheme_levels
    WHERE scheme_id = p_scheme_id
      AND parent_level_id IS NULL
  ) <> 1 THEN
    RAISE EXCEPTION 'El esquema debe tener exactamente un nivel raíz';
  END IF;

  IF EXISTS (
    WITH RECURSIVE walk AS (
      SELECT sl.scheme_level_id,
             CASE WHEN sl.is_search_terminal THEN 1 ELSE 0 END AS terminal_count
      FROM scheme_levels AS sl
      WHERE sl.scheme_id = p_scheme_id
        AND sl.parent_level_id IS NULL
      UNION ALL
      SELECT child.scheme_level_id,
             parent.terminal_count
               + CASE WHEN child.is_search_terminal THEN 1 ELSE 0 END
      FROM scheme_levels AS child
      JOIN walk AS parent
        ON child.parent_level_id = parent.scheme_level_id
      WHERE child.scheme_id = p_scheme_id
    )
    SELECT 1
    FROM walk AS node
    WHERE NOT EXISTS (
      SELECT 1
      FROM scheme_levels AS child
      WHERE child.scheme_id = p_scheme_id
        AND child.parent_level_id = node.scheme_level_id
    )
      AND node.terminal_count <> 1
  ) THEN
    RAISE EXCEPTION 'Cada rama raíz-hoja debe contener exactamente un terminal de búsqueda';
  END IF;
END;
$$;

-- Valida la jerarquía de locations y restringe rangos a terminales y etapas válidas.
CREATE OR REPLACE FUNCTION validate_location_tree_and_range()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  expected_parent_level_id INTEGER;
  actual_parent_level_id   INTEGER;
  level_is_terminal        BOOLEAN;
  scheme_stage             scheme_status;
BEGIN
  SELECT sl.parent_level_id, sl.is_search_terminal
  INTO expected_parent_level_id, level_is_terminal
  FROM scheme_levels AS sl
  WHERE sl.scheme_id = NEW.scheme_id
    AND sl.scheme_level_id = NEW.scheme_level_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El nivel de la ubicación no existe en el esquema';
  END IF;

  IF NEW.parent_location_id IS NULL THEN
    IF expected_parent_level_id IS NOT NULL THEN
      RAISE EXCEPTION 'Una ubicación raíz debe usar el nivel raíz';
    END IF;
  ELSE
    SELECT parent.scheme_level_id
    INTO actual_parent_level_id
    FROM locations AS parent
    WHERE parent.scheme_id = NEW.scheme_id
      AND parent.location_id = NEW.parent_location_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'La ubicación padre no existe en el mismo esquema';
    END IF;

    IF actual_parent_level_id IS DISTINCT FROM expected_parent_level_id THEN
      RAISE EXCEPTION 'El nivel de la ubicación hija no corresponde al nivel de su padre';
    END IF;
  END IF;

  IF TG_OP = 'UPDATE' AND NEW.parent_location_id IS NOT NULL AND EXISTS (
    WITH RECURSIVE descendants AS (
      SELECT l.location_id
      FROM locations AS l
      WHERE l.scheme_id = NEW.scheme_id
        AND l.parent_location_id = NEW.location_id
      UNION ALL
      SELECT child.location_id
      FROM locations AS child
      JOIN descendants AS parent
        ON child.parent_location_id = parent.location_id
      WHERE child.scheme_id = NEW.scheme_id
    )
    SELECT 1
    FROM descendants
    WHERE location_id = NEW.parent_location_id
  ) THEN
    RAISE EXCEPTION 'La relación propuesta produciría un ciclo de ubicaciones';
  END IF;

  IF NEW.range_start_key IS NOT NULL AND NOT level_is_terminal THEN
    RAISE EXCEPTION 'Solo una ubicación terminal de búsqueda puede contener un rango';
  END IF;

  SELECT status
  INTO scheme_stage
  FROM schemes
  WHERE scheme_id = NEW.scheme_id;

  IF NEW.range_start_key IS NOT NULL
     AND scheme_stage NOT IN ('PARTIALLY_ASSIGNED', 'ASSIGNED')
  THEN
    RAISE EXCEPTION 'Los rangos solo pueden asignarse desde PARTIALLY_ASSIGNED';
  END IF;

  IF NEW.range_start_key IS NULL AND scheme_stage = 'ASSIGNED' THEN
    RAISE EXCEPTION 'No se puede retirar un rango mientras el esquema está ASSIGNED';
  END IF;

  RETURN NEW;
END;
$$;

-- Limita los cambios estructurales de locations a LEVELS_DEFINED.
CREATE OR REPLACE FUNCTION ensure_location_structure_editable()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  affected_scheme_id INTEGER;
  affected_status    scheme_status;
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.scheme_id IS DISTINCT FROM NEW.scheme_id AND EXISTS (
    SELECT 1
    FROM schemes
    WHERE scheme_id IN (OLD.scheme_id, NEW.scheme_id)
      AND status <> 'LEVELS_DEFINED'
  ) THEN
    RAISE EXCEPTION 'Las locations solo pueden moverse entre esquemas en estado LEVELS_DEFINED';
  END IF;

  affected_scheme_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.scheme_id ELSE NEW.scheme_id END;

