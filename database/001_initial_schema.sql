-- Mantiene en un esquema común la capa, el nivel representado y el drilldown.
CREATE OR REPLACE FUNCTION validate_map_layer_level()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  layer_scheme      INTEGER;
  level_scheme      INTEGER;
  drilldown_scheme  INTEGER;
  layer_mode        map_render_mode;
BEGIN
  SELECT scheme_id, render_mode
  INTO layer_scheme, layer_mode
  FROM map_layers
  WHERE map_layer_id = NEW.map_layer_id;

  SELECT scheme_id
  INTO level_scheme
  FROM scheme_levels
  WHERE scheme_level_id = NEW.scheme_level_id;

  IF layer_scheme IS DISTINCT FROM level_scheme THEN
    RAISE EXCEPTION 'El MapLayer y el nivel representado deben pertenecer al mismo esquema';
  END IF;

  IF NEW.drilldown_map_layer_id IS NOT NULL THEN
    SELECT scheme_id
    INTO drilldown_scheme
    FROM map_layers
    WHERE map_layer_id = NEW.drilldown_map_layer_id;

    IF layer_scheme IS DISTINCT FROM drilldown_scheme THEN
      RAISE EXCEPTION 'El MapLayer de drilldown debe pertenecer al mismo esquema';
    END IF;
  END IF;

  IF layer_mode = 'TEMPLATE' AND EXISTS (
    SELECT 1
    FROM map_layer_scheme_levels
    WHERE map_layer_id = NEW.map_layer_id
      AND scheme_level_id <> NEW.scheme_level_id
  ) THEN
    RAISE EXCEPTION 'Un MapLayer TEMPLATE solo puede representar un nivel en esta versión';
  END IF;

  RETURN NEW;
END;
$$;

