-- Comprueba que render_mode sea compatible con niveles, SVG y asignaciones existentes.
CREATE OR REPLACE FUNCTION validate_map_layer()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.render_mode = 'TEMPLATE' AND (
    SELECT count(*)
    FROM map_layer_scheme_levels
    WHERE map_layer_id = NEW.map_layer_id
  ) > 1 THEN
    RAISE EXCEPTION 'Un MapLayer TEMPLATE solo puede representar un nivel en esta versión';
  END IF;

  IF NEW.render_mode = 'TEMPLATE' AND EXISTS (
    SELECT 1
    FROM map_layer_svgs
    WHERE map_layer_id = NEW.map_layer_id
      AND (variant_code IS NULL OR slot_count IS NULL)
  ) THEN
    RAISE EXCEPTION 'Los SVG existentes no son compatibles con el modo TEMPLATE';
  END IF;

  IF NEW.render_mode = 'STATIC' THEN
    IF EXISTS (
      SELECT 1
      FROM map_layer_svg_assignments
      WHERE map_layer_id = NEW.map_layer_id
    ) THEN
      RAISE EXCEPTION 'Un MapLayer STATIC no puede tener asignaciones de plantilla';
    END IF;

    IF EXISTS (
      SELECT 1
      FROM map_layer_svgs
      WHERE map_layer_id = NEW.map_layer_id
        AND slot_count IS NOT NULL
    ) THEN
      RAISE EXCEPTION 'Los SVG existentes no son compatibles con el modo STATIC';
    END IF;

    IF (
      SELECT count(*)
      FROM map_layer_svgs
      WHERE map_layer_id = NEW.map_layer_id
        AND enabled
    ) > 1 THEN
      RAISE EXCEPTION 'Un MapLayer STATIC solo puede tener un SVG habilitado';
    END IF;
  END IF;

  IF TG_OP = 'UPDATE' AND NEW.scheme_id IS DISTINCT FROM OLD.scheme_id AND (
    EXISTS (
      SELECT 1
      FROM map_layer_scheme_levels AS mlsl
      JOIN scheme_levels AS sl
        ON sl.scheme_level_id = mlsl.scheme_level_id
      WHERE mlsl.map_layer_id = NEW.map_layer_id
        AND sl.scheme_id <> NEW.scheme_id
    )
    OR EXISTS (
      SELECT 1
      FROM map_layer_svg_assignments AS a
      JOIN locations AS l
        ON l.location_id = a.context_location_id
      WHERE a.map_layer_id = NEW.map_layer_id
        AND l.scheme_id <> NEW.scheme_id
    )
    OR EXISTS (
      SELECT 1
      FROM map_layer_scheme_levels AS mlsl
      JOIN map_layers AS source_layer
        ON source_layer.map_layer_id = mlsl.map_layer_id
      WHERE mlsl.drilldown_map_layer_id = NEW.map_layer_id
        AND source_layer.scheme_id <> NEW.scheme_id
    )
  ) THEN
    RAISE EXCEPTION 'No se puede cambiar el esquema del MapLayer mientras tenga relaciones incompatibles';
  END IF;

  RETURN NEW;
END;
$$;

