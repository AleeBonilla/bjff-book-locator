-- Exige una raíz y la materialización de todos los niveles hijos esperados.
CREATE OR REPLACE FUNCTION assert_scheme_locations_defined(p_scheme_id INTEGER)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
  IF (
    SELECT count(*)
    FROM locations
    WHERE scheme_id = p_scheme_id
      AND parent_location_id IS NULL
  ) <> 1 THEN
    RAISE EXCEPTION 'El esquema debe tener exactamente una location raíz';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM locations AS parent
    JOIN scheme_levels AS expected_child_level
      ON expected_child_level.scheme_id = parent.scheme_id
     AND expected_child_level.parent_level_id = parent.scheme_level_id
    WHERE parent.scheme_id = p_scheme_id
      AND NOT EXISTS (
        SELECT 1
        FROM locations AS child
        WHERE child.scheme_id = parent.scheme_id
          AND child.parent_location_id = parent.location_id
          AND child.scheme_level_id = expected_child_level.scheme_level_id
      )
  ) THEN
    RAISE EXCEPTION 'Cada location debe materializar todos los niveles hijos definidos para su nivel';
  END IF;
END;
$$;

-- Controla transiciones de scheme_status y valida cada etapa antes de aceptarla.
CREATE OR REPLACE FUNCTION validate_scheme_state()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'DRAFT' THEN
      RAISE EXCEPTION 'Un esquema nuevo debe iniciar en DRAFT';
    END IF;

    RETURN NEW;
  END IF;

  IF OLD.status IS NOT DISTINCT FROM NEW.status THEN
    RETURN NEW;
  END IF;

  IF NOT (
    (OLD.status = 'DRAFT' AND NEW.status = 'LEVELS_DEFINED')
    OR (OLD.status = 'LEVELS_DEFINED' AND NEW.status IN ('DRAFT', 'LOCATIONS_DEFINED'))
    OR (OLD.status = 'LOCATIONS_DEFINED' AND NEW.status IN ('LEVELS_DEFINED', 'PARTIALLY_ASSIGNED'))
    OR (OLD.status = 'PARTIALLY_ASSIGNED' AND NEW.status IN ('LOCATIONS_DEFINED', 'ASSIGNED'))
    OR (OLD.status = 'ASSIGNED' AND NEW.status = 'PARTIALLY_ASSIGNED')
  ) THEN
    RAISE EXCEPTION 'Transición de estado no permitida: % -> %', OLD.status, NEW.status;
  END IF;

  IF NEW.status <> 'DRAFT' THEN
    PERFORM assert_scheme_search_coverage(NEW.scheme_id);
  END IF;

  IF NEW.status = 'DRAFT' AND (
    EXISTS (
      SELECT 1 FROM locations WHERE scheme_id = NEW.scheme_id
    )
    OR EXISTS (
      SELECT 1 FROM map_layers WHERE scheme_id = NEW.scheme_id
    )
  ) THEN
    RAISE EXCEPTION 'Un esquema con locations o MapLayers no puede volver a DRAFT';
  END IF;

  IF NEW.status = 'LEVELS_DEFINED' AND (
    EXISTS (
      SELECT 1
      FROM locations
      WHERE scheme_id = NEW.scheme_id
        AND range_start_key IS NOT NULL
    )
    OR EXISTS (
      SELECT 1 FROM map_layers WHERE scheme_id = NEW.scheme_id
    )
  ) THEN
    RAISE EXCEPTION 'Para volver a LEVELS_DEFINED deben eliminarse primero rangos y MapLayers';
  END IF;

  IF NEW.status = 'LOCATIONS_DEFINED' AND EXISTS (
    SELECT 1
    FROM locations
    WHERE scheme_id = NEW.scheme_id
      AND range_start_key IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'LOCATIONS_DEFINED no puede conservar rangos asignados';
  END IF;

  IF NEW.status IN ('LOCATIONS_DEFINED', 'PARTIALLY_ASSIGNED', 'ASSIGNED') THEN
    PERFORM assert_scheme_locations_defined(NEW.scheme_id);
  END IF;

  IF NEW.status = 'ASSIGNED' THEN
    IF NOT EXISTS (
      SELECT 1
      FROM locations AS l
      JOIN scheme_levels AS sl
        ON sl.scheme_id = l.scheme_id
       AND sl.scheme_level_id = l.scheme_level_id
      WHERE l.scheme_id = NEW.scheme_id
        AND sl.is_search_terminal
    ) THEN
      RAISE EXCEPTION 'El esquema debe contener ubicaciones terminales de búsqueda';
    END IF;

    IF EXISTS (
      SELECT 1
      FROM locations AS l
      JOIN scheme_levels AS sl
        ON sl.scheme_id = l.scheme_id
       AND sl.scheme_level_id = l.scheme_level_id
      WHERE l.scheme_id = NEW.scheme_id
        AND sl.is_search_terminal
        AND l.range_start_key IS NULL
    ) THEN
      RAISE EXCEPTION 'Todas las ubicaciones terminales deben tener un rango';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

