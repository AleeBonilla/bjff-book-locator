  INTO affected_status
  FROM schemes
  WHERE scheme_id = affected_scheme_id;

  IF affected_status <> 'LEVELS_DEFINED' THEN
    RAISE EXCEPTION 'La estructura de locations solo puede modificarse en estado LEVELS_DEFINED';
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;

