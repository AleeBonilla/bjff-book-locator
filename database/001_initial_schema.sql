-- Exige metadatos compatibles con STATIC o TEMPLATE y protege plantillas asignadas.
CREATE OR REPLACE FUNCTION validate_map_layer_svg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  layer_mode map_render_mode;
BEGIN
  SELECT render_mode
  INTO layer_mode
  FROM map_layers
  WHERE map_layer_id = NEW.map_layer_id;

  IF layer_mode = 'STATIC' THEN
    IF NEW.slot_count IS NOT NULL THEN
      RAISE EXCEPTION 'Un SVG STATIC no utiliza slot_count';
    END IF;

    IF NEW.enabled AND EXISTS (
      SELECT 1
      FROM map_layer_svgs
      WHERE map_layer_id = NEW.map_layer_id
        AND enabled
        AND map_layer_svg_id <> NEW.map_layer_svg_id
    ) THEN
      RAISE EXCEPTION 'Un MapLayer STATIC solo puede tener un SVG habilitado';
    END IF;
  ELSE
    IF NEW.variant_code IS NULL OR NEW.slot_count IS NULL THEN
      RAISE EXCEPTION 'Un SVG TEMPLATE requiere variant_code y slot_count';
    END IF;
  END IF;

  IF TG_OP = 'UPDATE'
     AND EXISTS (
       SELECT 1
       FROM map_layer_svg_assignments
       WHERE map_layer_svg_id = OLD.map_layer_svg_id
     )
     AND (
       NEW.map_layer_id IS DISTINCT FROM OLD.map_layer_id
       OR NEW.slot_count IS DISTINCT FROM OLD.slot_count
       OR (OLD.enabled AND NOT NEW.enabled)
     )
  THEN
    RAISE EXCEPTION 'Debe eliminar las asignaciones antes de modificar o deshabilitar esta plantilla';
  END IF;

  RETURN NEW;
END;
$$;

