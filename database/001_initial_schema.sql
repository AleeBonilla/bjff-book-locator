-- Comprueba esquema, nivel contextual, plantilla habilitada y cantidad de slots.
CREATE OR REPLACE FUNCTION validate_map_layer_svg_assignment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  layer_scheme        INTEGER;
  layer_mode          map_render_mode;
  location_scheme     INTEGER;
  context_level_id    INTEGER;
  represented_level   INTEGER;
  expected_parent     INTEGER;
  expected_slots      INTEGER;
  actual_slots        INTEGER;
BEGIN
  SELECT scheme_id, render_mode
  INTO layer_scheme, layer_mode
  FROM map_layers
  WHERE map_layer_id = NEW.map_layer_id;

  IF layer_mode <> 'TEMPLATE' THEN
    RAISE EXCEPTION 'Solo los MapLayers TEMPLATE aceptan asignaciones';
  END IF;

  SELECT scheme_id, scheme_level_id
  INTO location_scheme, context_level_id
  FROM locations
  WHERE location_id = NEW.context_location_id;

  IF layer_scheme IS DISTINCT FROM location_scheme THEN
    RAISE EXCEPTION 'La ubicación contextual y el MapLayer deben pertenecer al mismo esquema';
  END IF;

  SELECT min(scheme_level_id), count(*)
  INTO represented_level, actual_slots
  FROM map_layer_scheme_levels
  WHERE map_layer_id = NEW.map_layer_id;

  IF actual_slots <> 1 THEN
    RAISE EXCEPTION 'El MapLayer TEMPLATE debe representar exactamente un nivel';
  END IF;

  SELECT parent_level_id
  INTO expected_parent
  FROM scheme_levels
  WHERE scheme_level_id = represented_level;

  IF expected_parent IS DISTINCT FROM context_level_id THEN
    RAISE EXCEPTION 'La ubicación contextual debe pertenecer al nivel padre del nivel representado';
  END IF;

  SELECT slot_count
  INTO expected_slots
  FROM map_layer_svgs
  WHERE map_layer_id = NEW.map_layer_id
    AND map_layer_svg_id = NEW.map_layer_svg_id
    AND enabled;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El SVG asignado no existe, no pertenece al MapLayer o está deshabilitado';
  END IF;

  SELECT count(*)
  INTO actual_slots
  FROM locations
  WHERE scheme_id = layer_scheme
    AND parent_location_id = NEW.context_location_id
    AND scheme_level_id = represented_level;

  IF actual_slots <> expected_slots THEN
    RAISE EXCEPTION
      'La plantilla requiere % slots, pero la ubicación tiene % elementos representables',
      expected_slots,
      actual_slots;
  END IF;

  RETURN NEW;
END;
$$;

-- Valida cada selección de plantilla para una ubicación contextual.
CREATE TRIGGER map_layer_svg_assignments_validate
BEFORE INSERT OR UPDATE
ON map_layer_svg_assignments
FOR EACH ROW EXECUTE FUNCTION validate_map_layer_svg_assignment();

