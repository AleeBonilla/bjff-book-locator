-- Agrupa niveles, ubicaciones, rangos y mapas bajo una configuración publicable.
CREATE TABLE schemes (
  scheme_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 VARCHAR(80) NOT NULL,
  status               scheme_status NOT NULL DEFAULT 'DRAFT',
  short_description    VARCHAR(255),
  is_active            BOOLEAN NOT NULL DEFAULT false,
  enabled              BOOLEAN NOT NULL DEFAULT true,
  ordering_profile_id  INTEGER NOT NULL,
  created_by           INTEGER,
  published_by         INTEGER,
