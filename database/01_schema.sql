CREATE TABLE "location_distribution_settings" (
  "location_distribution_setting_id" INTEGER
    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "location_id" INTEGER NOT NULL,
  "scheme_id" INTEGER NOT NULL,
  "capacity_value" NUMERIC(10, 2),
  "capacity_unit" capacity_unit,
  "target_fill_ratio" NUMERIC(5, 4),
  "allow_overflow" BOOLEAN,
  "inherit_to_descendants" BOOLEAN NOT NULL DEFAULT false,
  "updated_by" INTEGER,
  "created_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updated_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "ck_location_settings_capacity_value"
    CHECK ("capacity_value" IS NULL OR "capacity_value" > 0),
  CONSTRAINT "ck_location_settings_capacity_pair"
    CHECK (("capacity_value" IS NULL) = ("capacity_unit" IS NULL)),
  CONSTRAINT "ck_location_settings_target_fill"
    CHECK (
      "target_fill_ratio" IS NULL
