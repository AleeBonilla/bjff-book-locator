CREATE TABLE "structure_templates" (
  "structure_template_id" SERIAL PRIMARY KEY,
  "name" VARCHAR(60) UNIQUE NOT NULL,
  "description" VARCHAR(255),
  "status" structure_template_status NOT NULL DEFAULT 'DRAFT',
  "enabled" BOOLEAN NOT NULL DEFAULT true,
  "created_by" INTEGER,
  "created_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updated_at" TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE "structure_template_nodes" (
  "structure_template_node_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "structure_template_id" INTEGER NOT NULL,
  "parent_template_node_id" INTEGER,
  "name" VARCHAR(40) NOT NULL,
  "role" location_role NOT NULL,
  "sort_order" INTEGER NOT NULL DEFAULT 0,
  "visual_kind" VARCHAR(40),
  "default_capacity_value" NUMERIC(10, 2),
  "default_capacity_unit" capacity_unit,
  "default_target_fill_ratio" NUMERIC(5, 4),
  "default_allow_overflow" BOOLEAN,
  "enabled" BOOLEAN NOT NULL DEFAULT true,
  "created_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updated_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "ck_template_nodes_capacity_value"
    CHECK ("default_capacity_value" IS NULL OR "default_capacity_value" > 0),
  CONSTRAINT "ck_template_nodes_capacity_pair"
    CHECK (
      ("default_capacity_value" IS NULL) =
      ("default_capacity_unit" IS NULL)
    ),
  CONSTRAINT "ck_template_nodes_target_fill"
    CHECK (
      "default_target_fill_ratio" IS NULL
      OR (
        "default_target_fill_ratio" > 0
        AND "default_target_fill_ratio" <= 1
      )
    ),
  CONSTRAINT "ck_template_nodes_not_self"
    CHECK ("parent_template_node_id" <> "structure_template_node_id")
);

