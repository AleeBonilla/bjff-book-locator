CREATE TABLE "distribution_runs" (
  "distribution_run_id" SERIAL PRIMARY KEY,
  "scheme_id" INTEGER NOT NULL,
  "collection_load_id" INTEGER NOT NULL,
  "based_on_distribution_run_id" INTEGER,
  "strategy" distribution_strategy NOT NULL DEFAULT 'HYBRID',
  "parameters" JSONB NOT NULL DEFAULT '{}'::jsonb,
  "status" process_status NOT NULL DEFAULT 'PENDING',
  "default_capacity_value" NUMERIC(10, 2),
  "default_capacity_unit" capacity_unit,
  "default_target_fill_ratio" NUMERIC(5, 4) NOT NULL DEFAULT 1,
  "default_allow_overflow" BOOLEAN NOT NULL DEFAULT true,
  "book_count" INTEGER NOT NULL DEFAULT 0,
  "position_count" INTEGER NOT NULL DEFAULT 0,
  "unassigned_count" INTEGER NOT NULL DEFAULT 0,
  "is_published" BOOLEAN NOT NULL DEFAULT false,
  "published_at" TIMESTAMPTZ,
  "error_message" TEXT,
  "created_by" INTEGER,
  "created_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "finished_at" TIMESTAMPTZ,
  CONSTRAINT "ck_distribution_default_capacity_value"
    CHECK (
      "default_capacity_value" IS NULL
      OR "default_capacity_value" > 0
    ),
  CONSTRAINT "ck_distribution_default_capacity_pair"
    CHECK (
      ("default_capacity_value" IS NULL) =
      ("default_capacity_unit" IS NULL)
    ),
  CONSTRAINT "ck_distribution_default_target_fill"
    CHECK (
      "default_target_fill_ratio" > 0
      AND "default_target_fill_ratio" <= 1
    ),
  CONSTRAINT "ck_distribution_counts"
    CHECK (
      "book_count" >= 0
      AND "position_count" >= 0
      AND "unassigned_count" >= 0
    ),
  CONSTRAINT "ck_distribution_published"
    CHECK (
      NOT "is_published"
      OR (
        "status" = 'DONE'
        AND "published_at" IS NOT NULL
      )
    )
